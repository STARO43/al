'use strict';
/* СЕАНС 08 — масштабы, плакат, финальная проверка, прощание. */
(function () {
  var A = TERM.ascii;
  function task(prompt, opts, fail) {
    return {
      choice: {
        prompt: prompt,
        opts: opts.map(function (o) {
          return { t: o[0], ok: !!o[1], wrong: o[2], formula: o[3] };
        }),
        fail: fail
      }
    };
  }

  TERM.register({
    id: 'sc08',
    title: 'ПОСЛЕДНИЙ СЕАНС',
    beats: [
      { sys: 'ВХОДЯЩАЯ ПЕРЕДАЧА · 03:17 · ВОСЬМОЙ СЕАНС · ПОСЛЕДНИЙ', center: true },
      { ab: 'Пора исполнить ставку. Первый вечер я обещал историю — она почти рассказана. Осталось главное: показать вам масштаб. Смотрите, как поле вариантов растёт в тысячи раз, а вопросы прибавляются по два-три.' },
      { anim: A.scales },
      { ab: 'От ста тысяч до восьми миллиардов — поле выросло в восемьдесят тысяч раз. Вопросов — с семнадцати до тридцати трёх. Вот вся моя сила: я расту не в разы, а в степени. Каждые +10 вариантов масштаба — всего +3–4 вопроса.' },
      { ab: 'И осталась одна строка, ради которой я вышел на связь. Выпишите её куда-нибудь.' },
      { anim: A.poster },
      { ab: 'Логарифм — это ответ на вопрос: В КАКУЮ СТЕПЕНЬ? a в степени x равно b — и логарифм от b по основанию a равен x. Одна связь, две записи, четыреста лет службы.' },
      { ab: 'Но прежде чем попрощаться — последняя проверка. Пять вопросов. Промахи разберу, как всегда, другими словами.' },

      task('1 из 5 — log₄(16) = ?', [
        ['2', true],
        ['4', false, 'Четырнадцать... нет: четыре — это ОСНОВАНИЕ. Спрашивается, сколько четвёрок перемножить до шестнадцати: 4 · 4 — два множителя.', { t: 'ПО-ДРУГОМУ', l: ['4² = 16  ← [[ok:2]]', '(а log₂(16) был бы 4 — не путайте основания)'] }],
        ['8', false, 'Восемь — половина от шестнадцати, но степени не делятся пополам: 4³ = 64. Считайте множители: 4 · 4 = 16 — их два.'],
        ['1/2', false, 'Половина — это log₄(2): корень из четырёх. А шестнадцать — два полных множителя-четвёрки.']
      ], 'Разбор: 4 · 4 = 16, два множителя → log₄(16) = 2.'),

      task('2 из 5 — Сколько вопросов нужно, чтобы гарантированно угадать число от 1 до 100?', [
        ['7', true],
        ['6', false, 'Шести не хватает: 2⁶ = 64, а число может оказаться в диапазоне 65–100. Перешагнуть сотню получается только на седьмом шаге: 2⁷ = 128.', { t: 'ПО-ДРУГОМУ', l: ['2⁶ = 64  < 100', '2⁷ = 128 ≥ 100  → [[ok:7]]'] }],
        ['10', false, 'Десять — с большим запасом: 2¹⁰ = 1024 различает больше тысячи. Гарантия — минимально достаточное число: округлённый вверх логарифм.'],
        ['100', false, 'Сто — это само поле вариантов. Если угадывать перебором — да. Но вы уже знаете способ лучше: делить пополам.']
      ], 'Разбор: ⌈log₂(100)⌉ = ⌈6,64⌉ = 7. Шестью вопросами различается только 64 варианта.'),

      task('3 из 5 — log₂(0,5) = ?', [
        ['−1', true],
        ['1', false, 'Единица — это 2¹ = 2. А у нас половина: мы СПУСКАЕМСЯ по лестнице, ниже единицы. Первая ступенька вниз — 2⁻¹ = 1/2.', { t: 'ПО-ДРУГОМУ', l: ['2⁻¹ = 1/2 = 0,5  → [[ok:−1]]'] }],
        ['2', false, 'Двойка — это 2² = 4: подъём вверх. А 0,5 — дробь, спуск.'],
        ['0,5', false, 'Вы перепутали аргумент с ответом: половина — это то, ЧТО мы ищем, а не степень. Найдите степень: 2 в какой степени даёт 1/2?']
      ], 'Разбор: 2⁻¹ = 1/2 = 0,5 → log₂(0,5) = −1.'),

      task('4 из 5 — Какое выражение не существует?', [
        ['log₃(−9)', true],
        ['log₂(8)', false, 'Существует: 2³ = 8. Три честных условия на месте: a = 2 > 0 и ≠ 1, b = 8 > 0.'],
        ['log₅(1)', false, 'Существует: 5⁰ = 1, ответ ноль. Единица — законный аргумент.'],
        ['lg(100)', false, 'Существует: 10² = 100. Ответ два.']
      ], 'Разбор: у log₃(−9) аргумент отрицателен. Ни одна степень тройки не даст минус девять — b > 0 нарушено.'),

      task('5 из 5 — Звук стал громче на +20 дБ. Интенсивность выросла…', [
        ['в 100 раз', true],
        ['в 20 раз', false, 'Децибелы — не проценты: шкала логарифмическая. Каждые +10 дБ — умножение на десять. Двадцать децибел — два таких шага.', { t: 'ПО-ДРУГОМУ', l: ['+10 дБ = ×10', '+20 дБ = ×10 · ×10 = [[ok:×100]]'] }],
        ['в 200 раз', false, 'Красивое число, но правило одно: +10 дБ — это ровно ×10. Два шага по десять — десять умножить на десять.'],
        ['в 10 000 раз', false, 'В десять тысяч раз — это +40 дБ. У нас только двадцать: два шага по десять.']
      ], 'Разбор: +20 дБ = 10² = ×100. Логарифмическая шкала: разы превращаются в сложение десятков.')
      ,
      { ab: 'Хватит. Вы считаете, как я. Осталось попрощаться.' },
      { pause: 600 },
      { ab: 'Когда услышите «60 дБ» — вспомните: это в миллион раз громче шёпота, но на шкале — короткий шаг. Когда увидите «+12% годовых» — вспомните: удвоение через шесть целых с чем-то лет, и я назову точную цифру. Когда магнитуда подскочит на единицу — не вздумайте подумать «на чуть-чуть».' },
      { ab: 'Я — логарифм. Я был у Непера в 1614-м, я в децибелах, в магнитудах, в вашем вкладе. И в тех семнадцати вопросах, что в первую ночь сжали сто тысяч вариантов в один.' },
      { ab: 'Связь будет прервана. Линия 07 закрывается. Прощайте — и не забывайте вопрос: в какую степень?' },
      { pause: 800 },
      { glitch: true },
      { sys: 'АБОНЕНТ ОТСОЕДИНИЛСЯ · 03:17', center: true },
      { big: 'ЛИНИЯ 07 · ТИШИНА' },
      { pause: 900 },
      { say: 'СВЯЗЬ ЗАМКНУТА НА САМОГО СЕБЯ · ДОСТУПЕН РЕЖИМ ТРЕНАЖЁРА' },
      {
        ask: {
          prompt: 'Линия свободна. Куда направимся?',
          opts: [
            { t: 'ТРЕНАЖЁР ▸', ok: true },
            { t: 'ПЕРЕЧИТАТЬ ИСТОРИЮ СНАЧАЛА', ok: true },
            { t: 'ЗАКРЫТЬ ТЕРМИНАЛ', ok: true }
          ],
          onPick: function (i) {
            if (i === 0) TERM.runSession(8);
            else if (i === 1) TERM.runSession(0);
            else TERM.api.sys('ТЕРМИНАЛ ОСТАЁТСЯ ВКЛЮЧЁННЫМ. ЛИНИЯ 07 — ТИШИНА.');
          }
        }
      }
    ]
  });
})();
