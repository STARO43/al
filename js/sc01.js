'use strict';
/* СЕАНС 01 — входящий вызов, ставка, игра «Угадаю ваше число» (1…100 000, ≤17 вопросов). */
(function () {
  var A = TERM.ascii, nb = TERM.nb;

  /* Контроллер игры: честный бинарный поиск по ответам пользователя */
  function gameAnim(box, api, done) {
    var status = A.gameStatus(box);
    (async function () {
      api.sys('ПРАВИЛА: ЗАГАДАЙТЕ ЦЕЛОЕ ЧИСЛО ОТ 1 ДО 100 000 И ЗАПИШИТЕ ЕГО.');
      api.sys('МНЕ ЕГО ГОВОРИТЬ НЕ НУЖНО. Я НАЙДУ ЕГО ВОПРОСАМИ.');
      var ready = 0;
      for (;;) {
        ready = await api.askRaw({
          prompt: 'Число загадано?',
          opts: [{ t: 'Да, загадал' }, { t: 'Подожди. Как это сработает?' }]
        });
        if (ready === 0) break;
        api.me('Подожди. Как это сработает?');
        await api.sayAb('Я не узнаю ваше число напрямую. Я задаю вопросы вида «ваше число больше N?» — и вы отвечаете только ДА или НЕТ. По вашим ответам я сужаю диапазон, пока в нём не останется одно число. Это и есть вся механика.');
      }
      api.me('Да, загадал');
      await api.sayAb('Хорошо. Тогда начинаем. И не пытайтесь меня обмануть: каждый ваш ответ для меня — чистая правда.');

      var lo = 1, hi = 100000, q = 0;
      var comments = {
        1: 'Сто тысяч вариантов. Начинаем делить.',
        5: 'Смотрите на счётчик: после пяти ответов живых вариантов в тридцать раз меньше.',
        9: 'Меньше двухсот. Диапазон сжался в пятьсот раз — за девять коротких ответов.',
        13: 'Тринадцать вариантов. Слышите, как тихо стало в линии?',
        16: 'Осталось два. Последний вопрос решает всё.'
      };
      while (hi > lo) {
        var m = lo + Math.floor((hi - lo) / 2);
        status.update(lo, hi, q + 1);
        var idx = await api.askRaw({
          prompt: 'ВОПРОС ' + (q + 1) + ': ваше число больше ' + nb(m) + '?',
          opts: [{ t: 'ДА' }, { t: 'НЕТ' }],
          row: true
        });
        api.me(idx === 0 ? 'ДА' : 'НЕТ');
        if (idx === 0) lo = m + 1; else hi = m;
        q++;
        if (comments[q]) await api.sayAb(comments[q]);
      }
      status.update(lo, hi, q);
      api.sys('ПОИСК ЗАВЕРШЁН');
      var big = api.line('ln--big', '');
      big.txt.textContent = 'ВАШЕ ЧИСЛО: ' + nb(lo);
      api.scroll();
      await api.sayAb('Если вы отвечали честно — это и есть ваше число. Перепроверьте. Я не знал его ни секунды до этого момента.');
      await api.sayAb('Семнадцать вопросов — и из ста тысяч вариантов осталось ровно один.');
      status.close();
      done();
    })();
  }

  TERM.register({
    id: 'sc01',
    title: 'ИГРА НА СТАВКУ',
    beats: [
      { sys: 'ВХОДЯЩАЯ ПЕРЕДАЧА · 03:17 · АБОНЕНТ НЕ ОПОЗНАН', center: true },
      {
        choice: {
          prompt: 'Принять передачу?',
          row: true,
          opts: [
            { t: 'ПРИНЯТЬ', ok: true },
            { t: 'ОТКЛОНИТЬ', flavor: 'Вызов повторится. Он всегда повторяется. У меня к вам разговор, который не терпит отлагательств.' },
            { t: 'КТО ЭТО?', flavor: 'Пока — просто линия 07. Примите передачу, и я представлюсь. Или хотя бы начну представляться.' }
          ]
        }
      },
      { me: 'ПРИНЯТЬ' },
      { pause: 700 },
      { glitch: true },
      { ab: 'Наконец-то. Три часа ночи, а вы всё ещё у экрана. Я знал, что вы ответите.' },
      { ab: 'Не ищите меня в журнале вызовов — меня там нет. И в списках абонентов не ищите. Зато у меня к вам предложение. Игра.' },
      { ab: 'Загадайте любое целое число от 1 до 100 000. Не говорите его мне. Я задам не более 17 вопросов, на которые отвечают ДА или НЕТ, — и назову ваше число.' },
      { ab: 'Угадаю — вы дослушаете мою историю до конца. Не угадаю — я отключусь и больше вас не побеспокою. Такая ставка.' },
      {
        choice: {
          prompt: 'Ваш ход:',
          opts: [
            { t: 'Принять игру', ok: true },
            { t: 'А если обманешь со счётом вопросов?', flavor: 'Считайте сами, я не обижусь. Счётчик вопросов будет перед вами на каждом шаге. Больше семнадцати — считайте, что я проиграл и исчез.' },
            { t: '17 вопросов — это много или мало?', flavor: 'Для ста тысяч возможностей — до смешного мало. Обычно-то их различают перебором: сто тысяч попыток. Мне хватит семнадцати. Сейчас покажу.' },
            { t: 'Я подумаю', retryPrompt: 'Ну так что: играем? Число можно загадать любое — от 1 до 100 000.', flavor: 'Думайте. Но линия не вечна, а история — длинная.' }
          ]
        }
      },
      { anim: gameAnim },
      { pause: 400 },
      {
        f: {
          t: 'ПОЧЕМУ ИМЕННО 17',
          l: [
            '2^16 = 65 536 < 100 000      ← шестнадцати не хватает',
            '2^17 = 131 072 ≥ 100 000     ← семнадцати хватает',
            '',
            '⌈log₂(100 000)⌉ = ⌈16,61⌉ = [[ok:17]]'
          ]
        }
      },
      { ab: 'Каждый вопрос — это выбор между двумя половинами. Вопросов хватило семнадцать, потому что два в семнадцатой степени — 131 072, а это больше ста тысяч. Но почему — об этом завтра, в это же время.' },
      { ab: 'Не выключайте связь.' },
      { sys: 'СЕАНС 01 ЗАВЕРШЁН · ЛИНИЯ ОСТАЁТСЯ ОТКРЫТОЙ', center: true },
      {
        ask: {
          prompt: 'Что дальше?',
          opts: [{ t: 'СЛЕДУЮЩИЙ СЕАНС ▸' }],
          onPick: function () { TERM.runSession(TERM.cur() + 1); }
        }
      }
    ]
  });
})();
