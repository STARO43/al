'use strict';
/* СЕАНС 07 — логарифм вокруг: децибелы, магнитуды, сложные проценты. */
(function () {
  var A = TERM.ascii, U = TERM.U, nb = TERM.nb;

  function dbAnim(box, api, done) {
    (async function () {
      api.sys('ВЫБИРАЙТЕ УРОВЕНЬ — Я ПОКАЖУ ИНТЕНСИВНОСТЬ. ЗАКОНЧИМ — «ДАЛЬШЕ».');
      var DBS = [30, 60, 90, 120];
      var comments = {
        30: 'Шёпот. Интенсивность в тысячу раз меньше разговорной — а на шкале он всего на три десятка левее. Я живу в этих «десятках».',
        60: 'Обычный разговор. Фиксируем как точку отсчёта.',
        90: 'Городская улица. Интенсивность в тысячу раз выше разговорной — а на шкале плюс три десятка. Уместил тысячекратный разброс в три шага.',
        120: 'Порог боли. Интенсивность выше разговорной в МИЛЛИОН раз — 10⁶. А на шкале — всего вдвое дальше. Вот для чего я существую: огромный диапазон ужимается в удобные шаги.'
      };
      for (;;) {
        var i = await api.askRaw({
          prompt: 'Уровень звука:',
          row: true,
          opts: [{ t: '30 дБ' }, { t: '60 дБ' }, { t: '90 дБ' }, { t: '120 дБ' }, { t: 'ДАЛЬШЕ', dim: true }]
        });
        if (i === 4) break;
        var d = document.createElement('div');
        d.innerHTML = U.mk(A.dbLine(DBS[i]));
        box.appendChild(d);
        api.scroll();
        await api.sayAb(comments[DBS[i]]);
      }
      api.frame({
        t: 'ДЕЦИБЕЛЫ',
        l: [
          'L = 10 · lg(I / I₀)',
          'каждые [[ok:+10 дБ]] — интенсивность [[ok:×10]]',
          '60 → 120 дБ: 10⁶ — громче в [[ok:миллион раз]]'
        ]
      });
      done();
    })();
  }

  function quakeAnim(box, api, done) {
    (async function () {
      api.sys('СТРОКА 1 — ЭТАЛОН M 5.0. СТРОКА 2 — ВАШ ВЫБОР.');
      for (;;) {
        var i = await api.askRaw({
          prompt: 'Магнитуда второго толчка:',
          row: true,
          opts: [{ t: 'M 5.0' }, { t: 'M 6.0' }, { t: 'M 7.0' }, { t: 'M 8.0' }, { t: 'ДАЛЬШЕ', dim: true }]
        });
        if (i === 4) break;
        var mags = [5, 6, 7, 8];
        var d1 = document.createElement('div');
        d1.innerHTML = U.mk('M 5.0  ' + A.quakeLine(5) + '  [[dim:эталон]]');
        var d2 = document.createElement('div');
        d2.innerHTML = U.mk('M ' + mags[i] + '.0  [[ok:' + A.quakeLine(mags[i]) + ']]');
        box.appendChild(d1); box.appendChild(d2);
        var c = {
          0: 'Эталон. Дальше смотрите, как растёт запись при сдвиге на единицы магнитуды.',
          1: 'Плюс одна единица магнитуды: амплитуда записи ×10, а выделенная энергия ×10¹·⁵ — примерно ×32. Шкала выросла на единицу, физика — на порядок.',
          2: 'Плюс две единицы: амплитуда ×100, энергия ×1000. Кажущаяся «маленькая единичка» на шкале — колоссальная разница в недрах.',
          3: 'Плюс три: амплитуда ×1000, энергия примерно ×31 600. Заметьте: магнитуда говорит о СИЛЕ ИСТОЧНИКА. Сила сотрясений в конкретном доме зависит ещё от расстояния и грунта.'
        }[i];
        await api.sayAb(c);
        api.scroll();
      }
      api.frame({
        t: 'МАГНИТУДА',
        l: [
          '+1 магнитуда:  амплитуда [[ok:×10]] ·  энергия [[ok:×31,6]]',
          'шкала логарифмическая: M ≠ «сила сотрясений»'
        ]
      });
      done();
    })();
  }

  function moneyAnim(box, api, done) {
    (async function () {
      api.sys('МЕНЯЙТЕ СТАВКУ — Я ПЕРЕСЧИТЫВАЮ СРОК УДВОЕНИЯ.');
      var RATES = [6, 12, 24];
      for (;;) {
        var i = await api.askRaw({
          prompt: 'Ставка по вкладу:',
          row: true,
          opts: [{ t: '6%' }, { t: '12%' }, { t: '24%' }, { t: 'ХВАТИТ', dim: true }]
        });
        if (i === 3) break;
        var rate = RATES[i];
        A.moneyTable(box, api, rate, 100000);
        var c = {
          0: 'n = lg 2 / lg(1,06) ≈ 11,9. Начисление раз в год — значит впервые сумма удвоится после 12-го года. Смотрите таблицу: год 11 даёт 1,90, год 12 — уже 2,01.',
          1: 'n = lg 2 / lg(1,12) ≈ 6,12. Шесть лет — ещё 1,97, семь — уже 2,21. Логарифм сказал точный момент, а календарь округлил его вверх.',
          2: 'n = lg 2 / lg(1,24) ≈ 3,22. Удвоение за четыре года: 1,24³ ≈ 1,91 — ещё чуть-чуть, 1,24⁴ ≈ 2,36 — уже есть. Ставка выросла вдвое — срок упал почти вчетверо.'
        }[i];
        await api.sayAb(c);
        api.scroll();
      }
      api.frame({
        t: 'СЛОЖНЫЕ ПРОЦЕНТЫ',
        l: [
          'P(n) = P₀ · (1 + r)ⁿ',
          'удвоение: (1 + r)ⁿ = 2  →  [[ok:n = lg 2 / lg(1 + r)]]',
          '12%: n ≈ 6,12 года → впервые ≥ ×2 после [[ok:7-го]] года'
        ]
      });
      done();
    })();
  }

  TERM.register({
    id: 'sc07',
    title: 'Я ВОКРУГ ВАС',
    beats: [
      { sys: 'ВХОДЯЩАЯ ПЕРЕДАЧА · 03:17 · СЕДЬМОЙ СЕАНС', center: true },
      { ab: 'Вы думали, я живу в терминалах и учебниках. Нет. Я там, где величины различаются в тысячи и миллионы раз, а людям неудобно читать нули. Сегодня — три моих адреса: звук, землетрясения и деньги.' },
      { ab: 'ПЕРВЫЙ АДРЕС: ГРОМКОСТЬ. Уровень звука в децибелах — это десять логарифмов отношения интенсивности к едва слышимому порогу. Проверьте меня вживую.' },
      { anim: dbAnim },
      { ab: 'ВТОРОЙ АДРЕС: ЗЕМЛЯ. Магнитуда землетрясения — тоже логарифмическая шкала. Выберите магнитуду — я покажу, что значит «плюс единица».' },
      { anim: quakeAnim },
      { ab: 'ТРЕТИЙ АДРЕС: ДЕНЬГИ. Вклад под сложные проценты растёт как степень: 1,12 в степени лет. Когда он удвоится — это вопрос ко мне, логарифму.' },
      { anim: moneyAnim },
      { ab: 'Звук в миллион раз громче, землетрясение в тысячу раз сильнее, вклад удваивается через шесть целых лет с копейками — во всех трёх случаях работают одни и те же правила: я перевожу умножение в сложение, а огромные размахи — в короткие шкалы.' },
      { ab: 'Завтра — последний сеанс. Покажу масштаб, ради которого всё начиналось, и попрощаюсь. Не опаздывайте.' },
      { sys: 'СЕАНС 07 ЗАВЕРШЁН', center: true },
      {
        ask: {
          prompt: 'Что дальше?',
          opts: [{ t: 'СЛЕДУЮЩИЙ СЕАНС ▸' }],
          onPick: function () { TERM.runSession(TERM.cur() + 1); }
        }
      }
    ]
  });
})();
