'use strict';
/* СЕАНС 04 — проверка на деле: шесть задач и квиз, все ответы — только выбор. */
(function () {
  var T = TERM;
  /* Собирает биту-задачу: opts = [подпись, верно?, разбор при промахе] */
  function task(prompt, opts, fail) {
    return {
      choice: {
        prompt: prompt,
        opts: opts.map(function (o) {
          return { t: o[0], ok: !!o[1], wrong: o[2], formula: o[3] };
        }),
        fail: fail
      }
    };
  }

  TERM.register({
    id: 'sc04',
    title: 'ПРОВЕРКА НА ДЕЛЕ',
    beats: [
      { sys: 'ВХОДЯЩАЯ ПЕРЕДАЧА · 03:17 · ЧЕТВЁРТЫЙ СЕАНС', center: true },
      { ab: 'Доверие проверяется делом. Шесть задач — отвечайте, я разберу каждый промах. Не бойтесь ошибаться: разбор промаха полезнее верного ответа.' },
      { ab: 'Подсказка одна на все шесть: я всегда отвечаю на вопрос «в какую степень?».' },

      task('ЗАДАЧА 1 из 6 — log₃(81) = ?', [
        ['4', true],
        ['3', false, 'Три — это log₃(27): 3 · 3 · 3 = 27. До восьмидесяти одного не хватает ещё одного умножения.', { t: 'ПО-ДРУГОМУ', l: ['3² = 9', '3³ = 27', '3⁴ = 81   ← сколько множителей? [[ok:4]]'] }],
        ['81', false, 'Восемьдесят один — сам аргумент, то, что получается. А спрашивали: сколько троек перемножить. Считайте шаги: 3 → 9 → 27 → 81.'],
        ['9', false, 'Девять — это 3², промежуточная ступенька. Двигайтесь дальше: 9 · 3 = 27, 27 · 3 = 81.']
      ], 'Разбор: 3 · 3 · 3 · 3 = 81 — четыре множителя, значит log₃(81) = 4.'),

      { ab: 'Верно. Следующая — про десятичный логарифм. Его пишут коротко: lg. Основание у него всегда десять.' },

      task('ЗАДАЧА 2 из 6 — lg(1000) = ?', [
        ['3', true],
        ['2', false, 'Два — это lg(100): сто — это 10². Тысяча — 10 · 10 · 10. Считайте нули: их три.', { t: 'ПО-ДРУГОМУ', l: ['10¹ = 10', '10² = 100', '10³ = 1000  ← [[ok:3]]'] }],
        ['4', false, 'Четыре — это lg(10 000): у него четыре нуля. У тысячи нулей три.'],
        ['10', false, 'Десять — это основание, а не показатель. Вопрос не «чему равно», а «в какую степень возвести 10».']
      ], 'Разбор: 10 · 10 · 10 = 1000 — три множителя-десятки, lg(1000) = 3.'),

      { ab: 'Хорошо. Теперь ловушка, на которой спотыкаются почти все. Она про единицу.' },

      task('ЗАДАЧА 3 из 6 — log₅(1) = ?', [
        ['0', true],
        ['1', false, 'Один — это log₅(5): один раз умножили пять на себя. А чтобы получить единицу, умножать не нужно вовсе. 5⁰ = 1.', { t: 'ПО-ДРУГОМУ', l: ['5¹ = 5', '5² = 25', '5⁰ = 1  ← «никогда» = [[ok:0]] раз'] }],
        ['5', false, 'Пять — это основание. Спрашивается не «чему равно», а «сколько раз умножить 5, чтобы вышло 1». Ответ: ни разу.'],
        ['−1', false, 'Минус один — это 5⁻¹ = 1/5 = 0,2. А нам нужна единица: она на ступеньку выше, на нулевой.']
      ], 'Разбор: любое число (кроме нуля) в нулевой степени — единица: 5⁰ = 1, значит log₅(1) = 0.'),

      { ab: 'Половина пути. Теперь вниз — в отрицательные показатели. Там те же ступеньки, только лестница ведёт в дроби.' },

      task('ЗАДАЧА 4 из 6 — log₂(1/4) = ?', [
        ['−2', true],
        ['2', false, 'Плюс два — это log₂(4): числа растут. А у нас дробь — мы спускаемся по лестнице вниз: 1/2, 1/4. Каждый шаг вниз минус один.', { t: 'ПО-ДРУГОМУ', l: ['2⁻¹ = 1/2', '2⁻² = 1/4  ← [[ok:−2]]'] }],
        ['−4', false, 'Минус четыре — это 2⁻⁴ = 1/16. Слишком глубоко: нам нужна одна четвёртая, а это две ступеньки вниз от единицы.'],
        ['1/2', false, 'Одна вторая — это log₂(√2) или log₄(2): дробный показатель. А у нас аргумент — одна четвёртая: целые две ступеньки вниз: 1/2, потом 1/4.']
      ], 'Разбор: спускаемся от единицы: 2⁻¹ = 1/2, 2⁻² = 1/4. Значит log₂(1/4) = −2.'),

      { ab: 'Заметьте: отрицательный показатель — это не «странность», это спуск по той же лестнице. Последние две задачи — про дробные ответы. Они самые интересные.' },

      task('ЗАДАЧА 5 из 6 — log₄(2) = ?', [
        ['1/2', true],
        ['2', false, 'Двойка — это аргумент, то, к чему идём. Спрашивается: сколько четвёрок перемножить, чтобы вышло два. Четыре в первой — уже четыре. Перебор. А половина умножения?', { t: 'ПО-ДРУГОМУ', l: ['4^(1/2) — «пол-умножения»', 'это √4 = 2  ← [[ok:1/2]]'] }],
        ['−2', false, 'Минус два — это 4⁻² = 1/16: спуск в дроби. А двойка больше единицы — мы поднимаемся, но меньше полного шага: половина шага.'],
        ['4', false, 'Четыре — основание, а не ответ. Думайте про «полшага»: √4 = 2, значит показатель — половина.']
      ], 'Разбор: 4^(1/2) — это квадратный корень из четырёх, то есть 2. Значит log₄(2) = 1/2. Дробный показатель — извлечение корня.'),

      task('ЗАДАЧА 6 из 6 — log₂(100 000) ≈ ? (округлить вверх)', [
        ['17', true],
        ['16', false, 'Шестнадцать — это 2¹⁶ = 65 536. Меньше ста тысяч: до цели не хватает. Перешагнуть столетнюю отметку получается на следующем шаге.', { t: 'ПО-ДРУГОМУ', l: ['2¹⁶ = 65 536  ← мало', '2¹⁷ = 131 072 ← уже больше', 'значит [[ok:17]]'] }],
        ['20', false, 'Двадцать вопросов — это для миллиона: 2²⁰ = 1 048 576. У нас поле в десять раз меньше, хватает семнадцати.'],
        ['15', false, 'Пятнадцать — это 2¹⁵ = 32 768. До ста тысяч — даже не половина пути. Считайте ступеньки дальше.']
      ], 'Разбор: 2¹⁶ = 65 536 < 100 000 ≤ 131 072 = 2¹⁷. Округляем 16,61 вверх — получаем 17. Первый вечер, наша ставка.')
      ,
      { ab: 'Все шесть — одна и та же мысль в разных костюмах. Я могу быть четвёркой, нулём, минус двойкой и даже половиной. Но вопрос всегда один: в какую степень?' },
      {
        f: {
          t: 'ИТОГ ШЕСТИ ЗАДАЧ',
          l: [
            'log₃(81) = [[ok:4]]      log₄(2) = [[ok:1/2]]',
            'lg(1000) = [[ok:3]]      log₂(100 000) ≈ [[ok:16,61]] → 17',
            'log₅(1) = [[ok:0]]       log₂(1/4) = [[ok:−2]]'
          ]
        }
      },
      { ab: 'А теперь я покажу вам места, где меня нет. Это самое важное про меня: знать не только где я есть, но и где меня искать бесполезно.' },
      { sys: 'СЕАНС 04 ЗАВЕРШЁН', center: true },
      {
        ask: {
          prompt: 'Что дальше?',
          opts: [{ t: 'СЛЕДУЮЩИЙ СЕАНС ▸' }],
          onPick: function () { TERM.runSession(TERM.cur() + 1); }
        }
      }
    ]
  });
})();
